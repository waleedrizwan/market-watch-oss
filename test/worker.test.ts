import { env } from "cloudflare:test";
import { describe, expect, it } from "vitest";
import worker, { SECURITY_HEADERS, isPublic, type Env } from "../src/index";

const BASE = "https://market-watch.example";
const base = env as unknown as Env;
const locked: Env = { ...base, ACCESS_TEAM_DOMAIN: "", ACCESS_AUD: "", ALLOW_UNAUTHENTICATED: undefined };
const open: Env = { ...locked, ALLOW_UNAUTHENTICATED: "true" };
const configured: Env = { ...locked, ACCESS_TEAM_DOMAIN: "example", ACCESS_AUD: "aud" };

const call = (path: string, e: Env, init?: RequestInit) =>
  worker.fetch(new Request(BASE + path, init) as Request<unknown, IncomingRequestCfProperties>, e);

describe("access control", () => {
  it("locks the dashboard, scripts and data when Access isn't configured", async () => {
    for (const path of ["/", "/index.html", "/app.js", "/lib.js", "/data.json", "/vendor/chart.umd.min.js"]) {
      expect((await call(path, locked)).status, path).toBe(503);
    }
    const page = await (await call("/", locked)).text();
    expect(page).toContain("Private dashboard");
    expect(page).toContain("isn't switched on yet");
  });

  it("never leaks prices on the locked page", async () => {
    const page = await (await call("/data.json", locked)).text();
    expect(page).not.toMatch(/"chains"|DDR5|pending_pct/);
  });

  it("asks for sign-in, and rejects tokens it can't verify", async () => {
    expect((await call("/", configured)).status).toBe(401);
    expect((await call("/data.json", configured, { headers: { "Cf-Access-Jwt-Assertion": "not-a-jwt" } })).status).toBe(403);
    expect((await call("/", configured, { headers: { Cookie: "CF_Authorization=garbage" } })).status).toBe(403);
  });

  it("keeps the privacy policy and its assets public", async () => {
    for (const path of ["/privacy", "/styles.css", "/favicon.svg", "/robots.txt", "/healthz", "/fonts/inter-latin-wght-normal.woff2"]) {
      expect((await call(path, locked)).status, path).toBe(200);
    }
    expect(await (await call("/privacy", locked)).text()).toContain("Privacy policy");
    expect(await (await call("/robots.txt", locked)).text()).toContain("Disallow: /");
  });

  it("only treats the intended paths as public", () => {
    expect(isPublic("/privacy")).toBe(true);
    expect(isPublic("/fonts/x.woff2")).toBe(true);
    expect(isPublic("/data.json")).toBe(false);
    expect(isPublic("/fonts")).toBe(false);
    expect(isPublic("/privacy/../data.json")).toBe(false);
  });

  it("rejects non-GET methods", async () => {
    const res = await call("/data.json", open, { method: "POST" });
    expect(res.status).toBe(405);
    expect(res.headers.get("Allow")).toBe("GET, HEAD");
  });
});

describe("serving the dashboard", () => {
  it("serves the page and its files once signed in, never cached publicly", async () => {
    const page = await call("/", open);
    expect(page.status).toBe(200);
    expect(page.headers.get("Cache-Control")).toBe("private, no-cache");
    expect(await page.text()).toContain('id="buckets"');

    // data.json is generated by build.py and isn't in the public repo, so check
    // a script that is: gated the same way, served once signed in.
    const script = await call("/lib.js", open);
    expect(script.status).toBe(200);
    expect(script.headers.get("Cache-Control")).toBe("private, no-cache");
    expect(await script.text()).toContain("export function indexed");
  });

  it("loads nothing from other origins", async () => {
    const html = await (await call("/", open)).text();
    const urls = [...html.matchAll(/(?:src|href)="([^"]+)"/g)].map((m) => m[1]!);
    const external = urls.filter((u) => /^(https?:)?\/\//.test(u));
    expect(external.every((u) => u.startsWith("https://github.com/"))).toBe(true);
    expect(html).not.toMatch(/<script>(?!\s*<\/script>)/); // no inline scripts (CSP)
    expect(html).not.toMatch(/\sstyle="/); // no inline styles (CSP)
  });

  it("sets security headers on every response", async () => {
    for (const [path, e] of [["/", open], ["/", locked], ["/data.json", configured], ["/privacy", locked], ["/healthz", locked], ["/nope", open]] as const) {
      const res = await call(path, e);
      for (const [k, v] of Object.entries(SECURITY_HEADERS)) expect(res.headers.get(k), `${path} ${k}`).toBe(v);
    }
  });

  it("returns 404 for missing files", async () => {
    expect((await call("/does-not-exist.js", open)).status).toBe(404);
  });
});
